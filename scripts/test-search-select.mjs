// Browser checks using local fixtures only; no production API or customer writes.
// Run with Playwright installed, or set PLAYWRIGHT_MODULE to its index.mjs path.
import assert from 'node:assert/strict'
import { createServer } from 'vite'
const { chromium } = await import(process.env.PLAYWRIGHT_MODULE || 'playwright')
const server = await createServer({ server: { host: '127.0.0.1', port: 5198, strictPort: true, proxy: {} } })
await server.listen()
let browser
try {
  browser = await chromium.launch({ headless: true })
  const page = await browser.newPage({ viewport: { width: 1100, height: 800 } })
  const errors = []
  page.on('pageerror', (error) => errors.push(error.message))
  await page.route('**/*', (route) => new URL(route.request().url()).hostname === '127.0.0.1' ? route.continue() : route.abort())
  await page.goto('http://127.0.0.1:5198/scripts/fixtures/search-select.html')
  const input = page.getByRole('combobox', { name: 'Member', exact: true })
  await input.fill('BeDa')
  await page.getByRole('option', { name: 'Ben Example — Beda Solutions' }).click()
  assert.equal(await page.getByTestId('value').textContent(), 'ben')
  assert.equal(await input.inputValue(), 'Ben Example — Beda Solutions')
  console.log('PASS company search and pointer selection preserve member ID')

  await input.fill('041122')
  assert.equal(await page.getByRole('option').count(), 1)
  await input.press('Enter')
  await page.getByRole('button', { name: 'Submit fixture' }).click()
  assert.equal(await page.getByTestId('submitted').textContent(), 'ben')
  console.log('PASS metadata search, Enter selection and native form value')

  await input.fill('level 4')
  await input.press('ArrowDown')
  assert.ok(await input.getAttribute('aria-activedescendant'))
  await input.press('Enter')
  assert.equal(await page.getByTestId('value').textContent(), 'amy')
  await input.fill('no-such-person')
  await page.getByRole('status').filter({ hasText: 'No matches' }).waitFor()
  await input.press('Enter')
  assert.equal(await page.getByTestId('value').textContent(), 'amy')
  await input.press('Escape')
  assert.equal(await input.inputValue(), 'Amy Example — Other Company')
  await input.fill('Ben')
  await input.press('Tab')
  assert.equal(await input.inputValue(), 'Amy Example — Other Company')
  console.log('PASS group search, keyboard selection, no matches and Escape')

  await input.fill('Ben')
  await input.press('ArrowDown')
  await input.press('ArrowDown')
  await input.press('Enter')
  assert.equal(await page.getByTestId('value').textContent(), 'ben')
  await input.click()
  await page.getByRole('option', { name: 'Unassigned' }).click()
  assert.equal(await page.getByTestId('value').textContent(), '')
  await page.getByRole('button', { name: 'Submit fixture' }).click()
  assert.equal(await input.getAttribute('aria-invalid'), 'true')
  assert.equal(await page.getByTestId('submitted').textContent(), 'ben')
  await input.press('Escape')
  await page.getByRole('button', { name: 'Set externally' }).click()
  assert.equal(await input.inputValue(), 'Amy Example — Other Company')
  await page.getByRole('button', { name: 'Toggle disabled' }).click()
  assert.equal(await input.isDisabled(), true)
  console.log('PASS disabled options, clearing, required validation and controlled updates')

  await page.getByRole('button', { name: 'Assign', exact: true }).click()
  const parkingMember = page.getByRole('combobox', { name: 'Member or contact' })
  await parkingMember.fill('beda')
  await page.getByRole('option', { name: 'Ben Example — Beda Solutions' }).click()
  await page.getByRole('button', { name: 'Save', exact: true }).click()
  assert.equal(await page.getByTestId('parking').textContent(), 'ben')
  console.log('PASS actual parking assignment saves the searched member')

  await page.getByRole('button', { name: 'Toggle disabled' }).click()
  await page.setViewportSize({ width: 390, height: 640 })
  await input.fill('ben@example.test')
  const box = await page.getByRole('listbox').boundingBox()
  assert.ok(box.x >= 0 && box.x + box.width <= 390 && box.y >= 0 && box.y + box.height <= 640)
  await page.getByRole('option', { name: 'Ben Example — Beda Solutions' }).click()
  assert.equal(await page.getByTestId('value').textContent(), 'ben')
  assert.deepEqual(errors, [])
  console.log('PASS mobile dropdown placement outside clipped container; no browser errors')

  const touch = await browser.newPage({ viewport: { width: 390, height: 640 }, hasTouch: true, isMobile: true })
  await touch.route('**/*', (route) => new URL(route.request().url()).hostname === '127.0.0.1' ? route.continue() : route.abort())
  await touch.goto('http://127.0.0.1:5198/scripts/fixtures/search-select.html')
  await touch.getByRole('combobox', { name: 'Member', exact: true }).fill('beda')
  await touch.getByRole('option', { name: 'Ben Example — Beda Solutions' }).tap()
  assert.equal(await touch.getByTestId('value').textContent(), 'ben')
  console.log('PASS touch selection')
} finally {
  await browser?.close()
  await server.close()
}
